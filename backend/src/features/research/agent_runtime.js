'use strict';

// H09 — the fixed bounded research pipeline (agent runtime).
//
// CONTRACTS §9: "The core implementation uses a fixed bounded Node pipeline in
// agent_runtime through existing modules and injected clients." This is NOT a
// generalized tool/stage runtime: there is exactly one bounded sequence —
// freeze context -> at most two synthesis/repair attempts -> deterministic
// server composition -> schema gate — with named budgets, explicit deadlines
// and real failed/limited statuses. Model clients are injected; nothing here
// performs live calls, holds credentials or mutates shared state.

const prompts = require('./prompts');
const validator = require('./result_validator');
const { profitAndLoss } = require('./metrics');

const PIPELINE_BUDGETS = Object.freeze({
  // CONTRACTS §8: "Core H09 permits at most two synthesis/repair attempts
  // total." Attempt 1 is the synthesis; attempt 2 is the single repair pass.
  MAX_SYNTHESIS_ATTEMPTS: 2,
  MAX_REPAIR_ATTEMPTS: 1,
  MAX_CONTEXT_EVIDENCE_ITEMS: prompts.CONTEXT_BUDGETS.MAX_CONTEXT_EVIDENCE_ITEMS,
});

const DEFAULT_COST_BASIS = 'raw_purchase';

const PIPELINE_VERSIONS = Object.freeze({
  contract: '1',
  pipeline: 'h09-bounded-agent',
  prompts: 'h09-v1',
  validator: 'h09-v1',
});

function pipelineError(code, message) {
  const error = new Error(message || code);
  error.code = code;
  return error;
}

function isPlainObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function pastDeadline(now, deadlineAt) {
  return typeof deadlineAt === 'string' && now().toISOString() > deadlineAt;
}

function dedupe(values) {
  return [...new Set(values)];
}

/**
 * Deterministic server-side economics composition from the exact owner-bound
 * position revision and a code-derived current price. Never regenerated by a
 * model; never derived from the market thesis.
 */
function composeEconomics(position, currentPrice) {
  if (position.state !== 'owned') {
    return { status: 'unavailable', reason: 'state_without_executed_economics' };
  }
  if (position.average_cost == null) {
    return { status: 'unavailable', reason: 'missing_average_cost' };
  }
  if (currentPrice == null) {
    return { status: 'unavailable', reason: 'missing_current_price' };
  }
  try {
    return profitAndLoss({
      average_cost: { amount: position.average_cost.amount, currency: position.average_cost.currency },
      current_price: { amount: currentPrice.amount, currency: currentPrice.currency },
      quantity: position.quantity,
      cost_adjustment_basis: position.average_cost.basis || DEFAULT_COST_BASIS,
      price_adjustment_basis: currentPrice.adjustment_basis,
    });
  } catch (error) {
    return { status: 'unavailable', reason: 'economics_input_invalid' };
  }
}

/**
 * Composes the owner-bound position_context for an assessment.
 *
 * economics_status carries the H01 contract semantics ("economics inputs
 * present on the position" — available / partial / unavailable), NOT P/L
 * computability. The authoritative P/L availability signal is the sibling
 * assessment.economics.status from composeEconomics. H09-N1 repair: this
 * composer deliberately takes no economics argument, so the two fields can
 * never be wired together. Renderers (H14/H15B) must never present
 * economics_status 'available' as comparable P/L when economics.status is
 * 'unavailable' (e.g. currency_mismatch).
 */
function composePositionContext(position) {
  const owned = position.state === 'owned';
  const hasCost = position.average_cost != null;
  const hasQuantity = position.quantity != null;
  const context = {
    position_id: position.position_id ?? null,
    instrument_id: position.instrument_id,
    state: position.state,
    revision: position.revision ?? null,
  };
  if (owned) {
    if (hasCost) context.average_cost = { amount: position.average_cost.amount, currency: position.average_cost.currency };
    if (hasQuantity) context.quantity = position.quantity;
    if (position.opened_on != null) context.opened_on = position.opened_on;
    // H01 semantics: economics inputs present, not P/L computability — see
    // the docblock above; economics.status is the P/L availability signal.
    context.economics_status = hasCost && hasQuantity ? 'available' : 'partial';
  } else {
    context.economics_status = 'unavailable';
  }
  return context;
}

function createResearchAgentRuntime({ modelClient, now, idFactory, isExchangeSession } = {}) {
  if (!modelClient || typeof modelClient.complete !== 'function') {
    throw new TypeError('createResearchAgentRuntime requires an injected model client');
  }
  if (typeof now !== 'function') {
    throw new TypeError('createResearchAgentRuntime requires an injected now() clock');
  }
  if (typeof idFactory !== 'function') {
    throw new TypeError('createResearchAgentRuntime requires an injected idFactory');
  }
  if (typeof isExchangeSession !== 'function') {
    throw new TypeError('createResearchAgentRuntime requires an isExchangeSession predicate');
  }

  /**
   * Run the bounded market synthesis + composition for one run/position
   * revision. Returns a result envelope compatible with H08 recordRunResult
   * ({position_revision, evidence_snapshot_id, session_as_of, status,
   * assessment}) on success, and a real failed status otherwise. Revision
   * conflicts throw REVISION_CONFLICT (publication as superseded is the
   * caller's transition).
   */
  async function runMarketSynthesis({
    run,
    snapshot,
    metrics,
    instrument,
    position,
    prior = null,
    currentPrice = null,
    deadlineAt,
  } = {}) {
    if (!isPlainObject(run) || !isPlainObject(snapshot) || !isPlainObject(position)) {
      throw pipelineError('INVALID_INPUT', 'run, snapshot and position are required');
    }

    // Exact owner-bound revision join BEFORE any model invocation.
    if (position.position_id !== run.position_id) {
      throw pipelineError('POSITION_MISMATCH', 'Position does not match the run position');
    }
    if (position.revision !== run.position_revision) {
      throw pipelineError('REVISION_CONFLICT', `Position revision ${position.revision} does not match run revision ${run.position_revision}`);
    }

    let modelCalls = 0;
    const failed = (error_code, extra = {}) => ({
      status: 'failed',
      error_code,
      model_calls: modelCalls,
      context_digest: null,
      ...extra,
    });

    if (pastDeadline(now, deadlineAt)) {
      return failed('DEADLINE_EXCEEDED');
    }

    // Coverage honesty: nothing to ground on is a failed run, not an invented
    // synthesis. Partial coverage proceeds to an explicitly limited result.
    const coverageStatus = snapshot.coverage?.status ?? 'unavailable';
    if (coverageStatus === 'unavailable' || !Array.isArray(snapshot.items) || snapshot.items.length === 0) {
      return failed('INSUFFICIENT_EVIDENCE');
    }

    // Freeze the bounded source context before any model invocation.
    const { context, digest } = prompts.buildMarketSynthesisContext({
      instrument,
      sessionAsOf: snapshot.session_as_of,
      cutoffAt: snapshot.cutoff_at,
      snapshot,
      metrics,
      position,
      prior,
      isExchangeSession,
    });

    const system = prompts.renderSynthesisSystemPrompt();
    let issues = [];
    let synthesis = null;

    for (let attempt = 1; attempt <= PIPELINE_BUDGETS.MAX_SYNTHESIS_ATTEMPTS; attempt += 1) {
      if (pastDeadline(now, deadlineAt)) {
        return failed('DEADLINE_EXCEEDED');
      }
      const request = {
        system,
        context,
        context_digest: digest,
        deadline_at: deadlineAt ?? null,
      };
      request.user = attempt === 1
        ? prompts.renderSynthesisUserPrompt(context)
        : prompts.renderRepairPrompt(context, issues);
      if (attempt > 1) request.issues = issues;

      let output;
      try {
        const response = await modelClient.complete(request);
        output = response?.output;
      } catch (error) {
        return failed('MODEL_CLIENT_FAILED', { validation_issues: [], client_error: error.message });
      }
      modelCalls += 1;

      // Server-owned normalization BEFORE validation: the server, not the
      // model, decides whether a prior report exists and which coverage gaps
      // are real. The validator then enforces grounding on the normalized
      // output.
      if (!context.prior && isPlainObject(output)) {
        output = { ...output, changes_since_previous: null };
      }
      if (coverageStatus !== 'available' && isPlainObject(output)) {
        output = { ...output, missing_data: dedupe([...(Array.isArray(output.missing_data) ? output.missing_data : []), ...context.coverage.gaps]) };
      }

      const verdict = validator.validateSynthesisOutput(output, context);
      if (verdict.ok) {
        synthesis = output;
        break;
      }
      issues = verdict.issues;
    }

    if (synthesis == null) {
      return failed('SYNTHESIS_VALIDATION_FAILED', { validation_issues: issues, context_digest: digest });
    }

    // ---- Deterministic server composition (no model involvement) ----
    const assessmentId = idFactory();
    const generatedAt = now().toISOString();
    const serverHorizons = new Map(context.horizons.map((h) => [h.horizon_months, h]));
    const coverageGaps = context.coverage.status !== 'available' ? [...context.coverage.gaps] : [];
    const missingData = dedupe([...(synthesis.missing_data ?? []), ...coverageGaps]);
    const status = context.coverage.status === 'available' ? 'complete' : 'limited';

    const economics = composeEconomics(position, currentPrice);

    const assessment = {
      id: assessmentId,
      contract_version: 1,
      position_id: position.position_id ?? null,
      position_revision: run.position_revision,
      instrument_id: run.instrument_id ?? instrument.instrument_id,
      run_id: run.id,
      evidence_snapshot_id: snapshot.snapshot_id,
      generated_at: generatedAt,
      session_as_of: context.session_as_of,
      status,
      market_thesis: synthesis.market_thesis,
      recommendation: synthesis.recommendation,
      position_context: composePositionContext(
        { ...position, instrument_id: run.instrument_id ?? instrument.instrument_id },
      ),
      changes_since_previous: synthesis.changes_since_previous ?? null,
      checkpoints: (Array.isArray(synthesis.checkpoints) ? synthesis.checkpoints : []).map((cp, index) => ({
        id: `${assessmentId}-cp-${index + 1}`,
        instrument_id: run.instrument_id ?? instrument.instrument_id,
        kind: cp.kind,
        metric_id: cp.metric_id ?? null,
        fixed_level: cp.fixed_level ?? null,
        condition: cp.condition,
        created_at: generatedAt,
        updated_at: generatedAt,
        status: cp.status,
        reason: cp.reason,
        source_assessment_id: assessmentId,
      })),
      outlooks: synthesis.outlooks.map((outlook) => {
        const server = serverHorizons.get(outlook.horizon_months);
        return {
          horizon_months: outlook.horizon_months,
          calendar_target_date: server.calendar_target_date,
          evaluation_session_date: server.evaluation_session_date,
          direction: outlook.direction,
          base_case: outlook.base_case,
          upside_case: outlook.upside_case,
          downside_case: outlook.downside_case,
          catalysts: outlook.catalysts ?? [],
          invalidators: outlook.invalidators ?? [],
          // H07A is a held follow-up: qualitative outlooks carry null.
          numeric_projection: null,
          data_limitations: outlook.data_limitations ?? [],
        };
      }),
      missing_data: missingData,
      next_review: null,
      versions: { ...PIPELINE_VERSIONS },
      // Additive server-composed owner-bound economics (schema passthrough
      // keeps it legal); the market thesis is never derived from these values.
      economics,
    };

    // Final canonical schema gate + exact binding check before persistence.
    let parsed;
    try {
      parsed = validator.parseAssessment(assessment);
    } catch (error) {
      return failed('ASSESSMENT_ASSEMBLY_INVALID', {
        validation_issues: error.issues?.map((entry) => ({
          code: 'SCHEMA_INVALID',
          path: entry.path.join('.'),
          message: entry.message,
        })) ?? [{ code: 'SCHEMA_INVALID', path: '', message: error.message }],
      });
    }
    const delivery = validator.validateAssessmentDelivery(parsed, {
      run,
      snapshot: { snapshot_id: snapshot.snapshot_id, instrument_id: snapshot.instrument_id, session_as_of: snapshot.session_as_of },
    });
    if (!delivery.ok) {
      return failed('ASSESSMENT_BINDING_INVALID', { validation_issues: delivery.issues });
    }

    return {
      status,
      result: {
        position_revision: run.position_revision,
        evidence_snapshot_id: snapshot.snapshot_id,
        session_as_of: context.session_as_of,
        status,
        assessment: parsed,
      },
      context_digest: digest,
      model_calls: modelCalls,
    };
  }

  return Object.freeze({ runMarketSynthesis });
}

module.exports = {
  PIPELINE_BUDGETS,
  PIPELINE_VERSIONS,
  composeEconomics,
  composePositionContext,
  createResearchAgentRuntime,
};
